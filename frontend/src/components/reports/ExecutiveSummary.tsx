import { Card } from "@/components/ui/Card";
import type { ExecutiveSummary as ExecutiveSummaryContent } from "@/lib/mock/reports";

interface ExecutiveSummaryProps {
  summary: ExecutiveSummaryContent;
}

const ROWS: { key: keyof ExecutiveSummaryContent; label: string }[] = [
  { key: "whatHappened", label: "What happened" },
  { key: "impact", label: "Impact" },
  { key: "investigated", label: "What was investigated" },
  { key: "conclusion", label: "What the investigation concluded" },
  { key: "afterAction", label: "What happened after the action" },
];

/**
 * The section a reader who only has a minute actually reads. Structured
 * into the five questions a report has to answer, rather than one prose
 * blob, so every report answers the same questions in the same order.
 * Static demo content — no summary is generated by a model.
 */
export function ExecutiveSummary({ summary }: ExecutiveSummaryProps) {
  return (
    <Card className="p-4 sm:p-6">
      <h3 className="text-base font-semibold text-foreground">Executive Summary</h3>
      <dl className="mt-4 space-y-4 text-sm">
        {ROWS.map((row) => (
          <div key={row.key}>
            <dt className="text-xs font-medium uppercase tracking-wide text-muted">{row.label}</dt>
            <dd className="mt-0.5 text-foreground">{summary[row.key]}</dd>
          </div>
        ))}
      </dl>
    </Card>
  );
}
